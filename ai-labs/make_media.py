"""Recreate constructed classroom media using only Python's standard library.

These are synthetic inputs, not speech, videos or outputs from an AI model.
"""

import json
import math
from pathlib import Path
import random
import struct
import wave


def main():
    target = Path(__file__).resolve().parent / "data"
    target.mkdir(parents=True, exist_ok=True)
    style = '<style>text{font-family:system-ui,sans-serif;fill:#172554} .note{font-size:16px} .title{font-size:24px;font-weight:650}</style>'
    shapes = '<circle cx="75" cy="115" r="24" fill="#2563eb"/><circle cx="145" cy="115" r="24" fill="#2563eb"/><rect x="55" y="170" width="45" height="45" fill="#ea580c"/><rect x="125" y="170" width="45" height="45" fill="#ea580c"/><path d="M220 95 L250 145 L190 145 Z" fill="#059669"/>'
    vision = '<svg xmlns="http://www.w3.org/2000/svg" width="800" height="320" viewBox="0 0 800 320">' + style
    vision += '<rect width="800" height="320" fill="#f8fafc"/><text x="25" y="40" class="title">构造图像：计数、文字与遮挡</text>'
    for offset, label in [(20, "A：无遮挡"), (410, "B：白色区域遮挡")]:
        vision += f'<g transform="translate({offset} 35)"><rect y="25" width="360" height="220" rx="12" fill="white" stroke="#cbd5e1"/>{shapes}'
        if offset == 410:
            vision += '<rect x="110" y="65" width="170" height="100" fill="white" stroke="#94a3b8" stroke-dasharray="5 4"/>'
        vision += f'<text x="15" y="55" class="note">{label}</text><text x="215" y="205" font-size="28">A0 · O1</text></g>'
    vision += '<text x="25" y="303" class="note">人为绘制的输入；不是视觉模型输出。遮挡后可见数量不等于真实数量。</text></svg>'
    (target / "vision-cards.svg").write_text(vision, encoding="utf-8")

    motion = '<svg xmlns="http://www.w3.org/2000/svg" width="880" height="360" viewBox="0 0 880 360">' + style
    motion += '<rect width="880" height="360" fill="#f8fafc"/><text x="24" y="35" class="title">构造运动帧：位置与身份一致性</text>'
    for row, label in enumerate(["A：保持身份", "B：第四帧变色"]):
        y = 65 + row * 140
        motion += f'<text x="24" y="{y+20}" class="note">{label}</text>'
        for i in range(4):
            left = 175 + i * 170
            color = "#dc2626" if row == 1 and i == 3 else "#2563eb"
            motion += f'<rect x="{left}" y="{y}" width="155" height="105" rx="8" fill="white" stroke="#cbd5e1"/><circle cx="{left+30+20*i}" cy="{y+52}" r="16" fill="{color}"/><text x="{left+12}" y="{y+94}" class="note">t={i}，x={20+20*i}</text>'
    motion += '<text x="24" y="345" class="note">人为帧序列，未运行视频/世界模型；一致性检查不能证明真实物理规律。</text></svg>'
    (target / "motion-frames.svg").write_text(motion, encoding="utf-8")

    rng = random.Random(42)
    rate, count = 16000, 16000
    clean = [0.5 * math.sin(2 * math.pi * 440 * i / rate) for i in range(count)]
    noisy = [max(-1.0, min(1.0, x + rng.uniform(-0.25, 0.25))) for x in clean]
    for filename, samples in [("audio-clean.wav", clean), ("audio-noisy.wav", noisy)]:
        with wave.open(str(target / filename), "wb") as audio:
            audio.setparams((1, 2, rate, count, "NONE", "not compressed"))
            audio.writeframes(struct.pack("<" + "h" * count, *(round(v * 32767) for v in samples)))
    truth = {
        "source": "Constructed teaching inputs, generated by make_media.py; no model output",
        "vision": {"before_occlusion": {"circles": 2, "squares": 2, "triangles": 1}, "text": "A0 · O1", "occluded_information": "one circle and the triangle are hidden"},
        "audio": {"kind": "synthetic tone, NOT speech or an ASR result", "sample_rate": rate, "seconds": 1, "frequency_hz": 440, "channels": 1, "sample_width_bytes": 2, "noise_seed": 42, "noise_amplitude": 0.25},
        "motion": {"kind": "constructed SVG frame sequence, NOT generated video", "x": [20, 40, 60, 80], "identity_counterexample": "row B changes blue to red at t=3"},
    }
    (target / "media-truth.json").write_text(json.dumps(truth, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
    print("Created two SVG inputs, two PCM WAV inputs, and media-truth.json")


if __name__ == "__main__":
    main()
